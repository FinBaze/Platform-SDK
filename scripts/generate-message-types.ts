/**
 * Writes `src/message-types.generated.ts`: one data type per message type, taken from the catalogue's
 * JSON Schemas, plus the `MessageType` union and `MessageData<T>` lookup. The output is committed so a
 * catalogue change shows up as a diff.
 *
 *   (in apps/api)  npx tsx scripts/export-message-catalogue.ts /tmp/message-catalogue.json
 *   (here)         FINBAZE_MESSAGE_CATALOGUE=/tmp/message-catalogue.json npx tsx scripts/generate-message-types.ts
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

type Schema = {
  type?: string | string[];
  properties?: Record<string, Schema>;
  required?: string[];
  items?: Schema;
  enum?: unknown[];
  anyOf?: Schema[];
  additionalProperties?: boolean | Schema;
};

type CatalogueType = {
  type: string;
  category: string;
  audiences: string[];
  priority: string;
  data: Schema;
};

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = process.env.FINBAZE_MESSAGE_CATALOGUE ?? join(root, '../../apps/api/dist/message-catalogue.json');
if (!existsSync(source)) {
  console.log(`No message catalogue at ${source}; keeping the committed types.`);
  process.exit(0);
}
const catalogue = JSON.parse(readFileSync(source, 'utf8')) as { categories: string[]; types: CatalogueType[] };

function ts(schema: Schema, indent: string): string {
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(' | ');
  if (schema.anyOf) return schema.anyOf.map((s) => ts(s, indent)).join(' | ');
  const type = Array.isArray(schema.type) ? schema.type[0] : schema.type;
  switch (type) {
    case 'string':
      return 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    case 'array':
      return `Array<${ts(schema.items ?? {}, indent)}>`;
    case 'object': {
      const props = Object.entries(schema.properties ?? {});
      if (props.length === 0) {
        const extra = schema.additionalProperties;
        return extra && typeof extra === 'object' ? `Record<string, ${ts(extra, indent)}>` : 'Record<string, never>';
      }
      const required = new Set(schema.required ?? []);
      const inner = `${indent}  `;
      const lines = props.map(([key, value]) => `${inner}${/^[A-Za-z_]\w*$/.test(key) ? key : JSON.stringify(key)}${required.has(key) ? '' : '?'}: ${ts(value, inner)};`);
      return `{\n${lines.join('\n')}\n${indent}}`;
    }
    default:
      return 'unknown';
  }
}

const pascal = (type: string) =>
  type
    .split(/[._]/)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('');

const out: string[] = [
  '// Generated by scripts/generate-message-types.ts from the message catalogue. Do not edit.',
  '',
  `export type MessageCategory = ${catalogue.categories.map((c) => JSON.stringify(c)).join(' | ')};`,
  '',
  `export type MessageType = ${catalogue.types.map((t) => JSON.stringify(t.type)).join(' | ')};`,
  '',
];
for (const t of catalogue.types) {
  out.push(`/** \`${t.type}\` (${t.category}, ${t.priority}). */`, `export type ${pascal(t.type)}Data = ${ts(t.data, '')};`, '');
}
out.push('export interface MessageDataByType {');
for (const t of catalogue.types) out.push(`  ${JSON.stringify(t.type)}: ${pascal(t.type)}Data;`);
out.push('}', '', '/** The `data` of a message of type `T`. */', 'export type MessageData<T extends MessageType = MessageType> = MessageDataByType[T];', '');

writeFileSync(join(root, 'src/message-types.generated.ts'), out.join('\n'));
console.log(`Wrote ${catalogue.types.length} message types.`);
